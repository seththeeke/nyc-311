#!/bin/sh
#
# agent-schedule-install.sh {install|uninstall|status|kick|render} <agent>
#
# Manages the per-agent launchd job on this machine. The generated plist is
# deliberately barebones — calendar times + one command — and only ever calls
# scripts/agent-scheduled-run.sh <agent> in this checkout; every bit of logic
# lives in the repo. Times come from SCHEDULE in
# scripts/agent-schedules/<agent>.env, each slot [Day@]HH:MM[=MODE] in the
# machine's local time (Pacific on the Mac mini). See
# docs/agent-automation-setup.md.
#
#   install    write ~/Library/LaunchAgents/com.nyc311.agent.<agent>.plist and
#              (re)load it — re-run after changing SCHEDULE
#   uninstall  unload and delete the plist
#   status     show launchd's view of the job
#   kick       start a run now (same path launchd takes), without waiting
#   render     print the plist install would write, without writing it
#              (scripts/agent-schedule-sync.sh compares it with the installed one)

set -eu

die() { printf 'agent-schedule-install: %s\n' "$*" >&2; exit 1; }

sub=${1:-}
agent=${2:-}
[ -n "$sub" ] && [ -n "$agent" ] || die "usage: agent-schedule-install.sh {install|uninstall|status|kick|render} <agent>"

script_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
config="$script_dir/agent-schedules/$agent.env"
[ -f "$config" ] || die "no schedule config at $config"

label="com.nyc311.agent.$agent"
plist="$HOME/Library/LaunchAgents/$label.plist"
domain="gui/$(id -u)"
log_dir="${AGENT_LOG_ROOT:-"$HOME/Library/Logs/nyc311-agents"}/$agent"

render_plist() {
  # shellcheck disable=SC1090
  . "$config"
  : "${SCHEDULE:?SCHEDULE not set in $config}"

  # A slot is [Day@]HH:MM[=MODE] (docs/17-executive-team.md §21.6): Day is
  # Sun..Sat for a weekly slot; MODE picks PROMPT_<MODE> at run time.
  intervals=""
  for slot in $SCHEDULE; do
    t=${slot%%=*}
    if [ "$t" != "$slot" ]; then
      case "${slot#*=}" in
        '' | [!A-Z]* | *[!A-Z0-9_]*) die "bad SCHEDULE mode in '$slot' (want ALL_CAPS)" ;;
      esac
    fi
    weekday=""
    case "$t" in
      *@*)
        case "${t%%@*}" in
          Sun) weekday=0 ;; Mon) weekday=1 ;; Tue) weekday=2 ;; Wed) weekday=3 ;;
          Thu) weekday=4 ;; Fri) weekday=5 ;; Sat) weekday=6 ;;
          *) die "bad SCHEDULE day in '$slot' (want Sun..Sat)" ;;
        esac
        t=${t#*@} ;;
    esac
    case "$t" in
      [0-2][0-9]:[0-5][0-9]) : ;;
      *) die "bad SCHEDULE time '$slot' (want [Day@]HH:MM[=MODE])" ;;
    esac
    h=${t%%:*}; m=${t#*:}
    h=${h#0}; m=${m#0}
    [ "${h:-0}" -le 23 ] || die "bad SCHEDULE hour in '$slot'"
    day_key=""
    [ -n "$weekday" ] && day_key="<key>Weekday</key><integer>$weekday</integer>"
    intervals="$intervals
    <dict>$day_key<key>Hour</key><integer>${h:-0}</integer><key>Minute</key><integer>${m:-0}</integer></dict>"
  done

  cat <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by scripts/agent-schedule-install.sh — edit SCHEDULE in scripts/agent-schedules/$agent.env, not this file. -->
<plist version="1.0">
<dict>
  <key>Label</key><string>$label</string>
  <key>ProgramArguments</key>
  <array>
    <string>/bin/sh</string>
    <string>$script_dir/agent-scheduled-run.sh</string>
    <string>$agent</string>
  </array>
  <key>StartCalendarInterval</key>
  <array>$intervals
  </array>
  <key>StandardOutPath</key><string>$log_dir/launchd.log</string>
  <key>StandardErrorPath</key><string>$log_dir/launchd.log</string>
</dict>
</plist>
EOF
}

cmd_install() {
  rendered=$(render_plist) || exit 1
  mkdir -p "$HOME/Library/LaunchAgents" "$log_dir"
  printf '%s\n' "$rendered" >"$plist"
  plutil -lint "$plist" >/dev/null || die "generated plist failed plutil -lint: $plist"
  # shellcheck disable=SC1090
  . "$config"

  launchctl bootout "$domain/$label" 2>/dev/null || true
  launchctl bootstrap "$domain" "$plist"
  printf 'installed %s — runs at %s (local time)\n' "$label" "$SCHEDULE"
}

cmd_uninstall() {
  launchctl bootout "$domain/$label" 2>/dev/null || true
  rm -f "$plist"
  printf 'uninstalled %s\n' "$label"
}

case "$sub" in
  install) cmd_install ;;
  uninstall) cmd_uninstall ;;
  status) launchctl print "$domain/$label" | grep -E 'state =|last exit code|runs =|path =' || die "$label not loaded" ;;
  render) render_plist ;;
  kick) launchctl kickstart "$domain/$label" && printf 'started %s — tail -f %s/*.log\n' "$label" "$log_dir" ;;
  *) die "usage: agent-schedule-install.sh {install|uninstall|status|kick|render} <agent>" ;;
esac
